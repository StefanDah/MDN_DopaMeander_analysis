function [VarName1, VarName2, VarName3, VarName4, VarName5] = fcn_Excelimport(workbookFile, sheetName, dataLines)
%IMPORTFILE Import data from a spreadsheet
%  [VARNAME1, VARNAME2, VARNAME3, VARNAME4, VARNAME5] = IMPORTFILE(FILE)
%  reads data from the first worksheet in the Microsoft Excel
%  spreadsheet file named FILE.  Returns the data as column vectors.
%
%  [VARNAME1, VARNAME2, VARNAME3, VARNAME4, VARNAME5] = IMPORTFILE(FILE,
%  SHEET) reads from the specified worksheet.
%
%  [VARNAME1, VARNAME2, VARNAME3, VARNAME4, VARNAME5] = IMPORTFILE(FILE,
%  SHEET, DATALINES) reads from the specified worksheet for the
%  specified row interval(s). Specify DATALINES as a positive scalar
%  integer or a N-by-2 array of positive scalar integers for
%  dis-contiguous row intervals.
%
%  Example:
%  [VarName1, VarName2, VarName3, VarName4, VarName5] = importfile("D:\Postdoc\Data\Matlab Analysis\Fly_ID.xlsx", "Sheet1", [1, 5]);
